// Populate exactly up to 423 episodes (matching the YouTube playlist)
for (const season of POKEMON_SEASONS) {
  if (season.id === 1) continue; // Season 1 is already populated

  for (let epInS = 1; epInS <= season.totalEpisodes; epInS++) {
    const epNum = season.startEpisode + epInS - 1;
    if (epNum > 423) break;

    const notable = NOTABLE_EXTRA_EPISODES[epNum];
    const sMeta = EXTENDED_SEASON_DATA[season.id] || { titlePrefix: season.shortName, pokemon: ["Pikachu"] };

    const baseTitle = notable?.titleDe || `${sMeta.titlePrefix} – Teil ${epInS}`;
    const cleanTitle = baseTitle.replace(/^Folge\s+\d+:\s*/i, "").trim();
    // Official YouTube playlist title format: [Episodentitel] | POKÉMON – GANZE FOLGE [Folgennr] | Staffel [Staffelnr]
    const exactTitleDe = `${cleanTitle} | POKÉMON – GANZE FOLGE ${epInS} | Staffel ${season.id}`;

    POKEMON_EPISODES.push({
      id: epNum,
      season: season.id,
      seasonName: season.name,
      episodeInSeason: epInS,
      titleDe: exactTitleDe,
      titleEn: notable?.titleEn || `Episode ${epNum}: ${season.shortName} Part ${epInS}`,
      summary: notable?.summary || `Ash und seine Freunde setzen ihr spannendes Abenteuer in der ${season.region}-Region fort. Sie trainieren für die Liga, treffen wilde Pokémon und müssen sich neuen Prüfungen und Team Rocket stellen.`,
      keyEvents: notable?.keyEvents || [
        `Abenteuer in der Region ${season.region}`,
        `Herausforderungen für Ash und seine Pokémon`,
        `Reisefortschritt in ${season.shortName}`
      ],
      pokemonFeatured: notable?.pokemon || sMeta.pokemon,
      badgeEarned: notable?.badge,
      durationMinutes: 21
    });
  }
}

// Ensure Season 1 also follows the exact YouTube title format: [Titel] | POKÉMON – GANZE FOLGE [Folgennr] | Staffel 1
for (const ep of POKEMON_EPISODES) {
  if (ep.season === 1 && !ep.titleDe.includes(" | POKÉMON – GANZE FOLGE ")) {
    const cleanTitle = ep.titleDe.replace(/^Folge\s+\d+:\s*/i, "").trim();
    ep.titleDe = `${cleanTitle} | POKÉMON – GANZE FOLGE ${ep.episodeInSeason} | Staffel 1`;
  }
}

export const TOTAL_EPISODES_COUNT = POKEMON_EPISODES.length;

export function getAllEpisodes(): Episode[] {
  return POKEMON_EPISODES;
}

export function getEpisodeById(id: number): Episode | undefined {
  return POKEMON_EPISODES.find(ep => ep.id === id);
}
